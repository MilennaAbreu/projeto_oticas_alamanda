CREATE TRIGGER trg_pontos_fidelidade
AFTER INSERT ON VENDAS
FOR EACH ROW
BEGIN
    DECLARE pontos INT;

    SET pontos = FLOOR(NEW.VALOR_TOTAL / 10);

    INSERT INTO FIDELIDADE_CLIENTE (ID_CLIENTE, PONTOS, ULTIMA_ATUALIZACAO)
    VALUES (NEW.ID_CLIENTE, pontos, CURRENT_TIMESTAMP)
    ON DUPLICATE KEY UPDATE
        PONTOS = PONTOS + VALUES(PONTOS),
        ULTIMA_ATUALIZACAO = CURRENT_TIMESTAMP;
END$$

