DELIMITER $$

CREATE TRIGGER trg_gerar_contas_receber
AFTER INSERT ON VENDAS
FOR EACH ROW
BEGIN
    DECLARE i INT DEFAULT 1;
    DECLARE vencimento DATE;
    DECLARE valor_parcela DECIMAL(10,2);
    
    SET valor_parcela = NEW.VALOR_TOTAL / NEW.NUMERO_PARCELAS;
    SET vencimento = NEW.DATA_VENCIMENTO_PARCELA;

    WHILE i <= NEW.NUMERO_PARCELAS DO
        INSERT INTO CONTAS_A_RECEBER (
            ID_VENDA, ID_CLIENTE, VALOR, DATA_VENCIMENTO, STATUS, ID_EMPRESA
        ) VALUES (
            NEW.ID, NEW.ID_CLIENTE, valor_parcela, DATE_ADD(vencimento, INTERVAL (i - 1) MONTH), 'PENDENTE', NEW.ID_EMPRESA
        );
        SET i = i + 1;
    END WHILE;
END$$

