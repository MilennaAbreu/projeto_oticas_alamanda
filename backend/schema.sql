DELIMITER $$

CREATE TRIGGER trg_gerar_contas_pagar
AFTER INSERT ON COMPRAS
FOR EACH ROW
BEGIN
    DECLARE i INT DEFAULT 1;
    DECLARE vencimento DATE DEFAULT NEW.DATA_VENCIMENTO_PARCELA;
    DECLARE valor_parcela DECIMAL(10,2);

    IF NEW.NUMERO_PARCELAS > 0 THEN
        SET valor_parcela = NEW.VALOR_TOTAL / NEW.NUMERO_PARCELAS;

        WHILE i <= NEW.NUMERO_PARCELAS DO
            INSERT INTO CONTAS_A_PAGAR (
                ID_COMPRA, ID_FORNECEDOR, VALOR_TOTAL, PARCELA, VALOR_PARCELA,
                DATA_VENCIMENTO, FORMA_PAGAMENTO, NUMERO_PARCELAS, STATUS, ID_EMPRESA
            ) VALUES (
                NEW.ID, NEW.ID_FORNECEDOR, NEW.VALOR_TOTAL, i, valor_parcela,
                DATE_ADD(vencimento, INTERVAL (i - 1) MONTH),
                NEW.FORMA_PAGAMENTO, NEW.NUMERO_PARCELAS, 'PENDENTE', NEW.ID_EMPRESA
            );
            SET i = i + 1;
        END WHILE;
    END IF;
END$$

