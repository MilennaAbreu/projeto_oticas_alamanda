CREATE TRIGGER trg_log_produto
AFTER UPDATE ON PRODUTO
FOR EACH ROW
BEGIN
    DECLARE mudancas TEXT DEFAULT '';

    IF OLD.NOME <> NEW.NOME THEN
        SET mudancas = CONCAT(mudancas, 'Nome alterado | ');
    END IF;
    IF OLD.VALOR_UNITARIO <> NEW.VALOR_UNITARIO THEN
        SET mudancas = CONCAT(mudancas, 'Valor alterado | ');
    END IF;
    IF OLD.ESTOQUE_ATUAL <> NEW.ESTOQUE_ATUAL THEN
        SET mudancas = CONCAT(mudancas, 'Estoque alterado | ');
    END IF;
    IF OLD.STATUS <> NEW.STATUS THEN
        SET mudancas = CONCAT(mudancas, 'Status alterado | ');
    END IF;

    IF mudancas <> '' THEN
        INSERT INTO LOG_ALTERACOES (TABELA, ID_REGISTRO, ACAO, DADOS_ANTIGOS, DADOS_NOVOS)
        VALUES ('PRODUTO', NEW.ID, 'UPDATE', 'Alterações detectadas', mudancas);
    END IF;
END$$

