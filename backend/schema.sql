CREATE OR REPLACE VIEW vw_estoque_empresa AS
SELECT 
    e.ID AS ID_EMPRESA,
    e.NOME AS EMPRESA,
    p.ID AS ID_PRODUTO,
    p.NOME AS PRODUTO,
    te.ESTOQUE_ATUAL
FROM ESTOQUE_EMPRESA te
JOIN EMPRESA e ON e.ID = te.ID_EMPRESA
JOIN PRODUTO p ON p.ID = te.ID_PRODUTO;


CREATE OR REPLACE VIEW vw_vendas_por_cliente AS
SELECT 
    c.ID AS ID_CLIENTE,
    c.NOME,
    COUNT(v.ID) AS TOTAL_VENDAS,
    SUM(v.VALOR_TOTAL) AS TOTAL_GASTO
FROM VENDAS v
JOIN CLIENTE c ON c.ID = v.ID_CLIENTE
GROUP BY c.ID, c.NOME;



