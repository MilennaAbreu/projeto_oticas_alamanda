DELIMITER $$

CREATE TRIGGER trg_reajuste_preco_produto
AFTER INSERT ON ITENS_COMPRA
FOR EACH ROW
BEGIN
    DECLARE margem DECIMAL(5,2) DEFAULT 50;
    DECLARE novo_preco DECIMAL(10,2);

    SELECT COALESCE(m.MARGEM_PERCENTUAL, 50)
    INTO margem
    FROM PRODUTO p
    LEFT JOIN MARGEM_LUCRO m ON m.ID_CATEGORIA = p.ID_CATEGORIA
    WHERE p.ID = NEW.ID_PRODUTO;

    SET novo_preco = NEW.VALOR_UNITARIO * (1 + (margem / 100.0));

    UPDATE PRODUTO
    SET VALOR_UNITARIO = ROUND(novo_preco, 2),
        DATA_ATUALIZACAO = CURRENT_TIMESTAMP
    WHERE ID = NEW.ID_PRODUTO;
END$$

