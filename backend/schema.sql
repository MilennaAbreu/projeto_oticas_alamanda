DELIMITER $$

CREATE TRIGGER trg_venda_estoque
AFTER INSERT ON ITENS_VENDA
FOR EACH ROW
BEGIN
    UPDATE PRODUTO 
    SET ESTOQUE_ATUAL = ESTOQUE_ATUAL - NEW.QUANTIDADE,
        DATA_ATUALIZACAO = CURRENT_TIMESTAMP
    WHERE ID = NEW.ID_PRODUTO;

    INSERT INTO LOG_ALTERACOES (TABELA, ID_REGISTRO, ACAO, DADOS_NOVOS, ID_USUARIO)
    SELECT 'PRODUTO', NEW.ID_PRODUTO, 'UPDATE', 'Estoque reduzido', v.ID_USUARIO
    FROM VENDAS v WHERE v.ID = NEW.ID_VENDA;
END$$

