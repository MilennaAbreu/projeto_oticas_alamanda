CREATE OR REPLACE VIEW vw_contas_receber_status AS
SELECT 
    cr.ID_CLIENTE,
    c.NOME,
    cr.STATUS,
    COUNT(*) AS QTDE,
    SUM(cr.VALOR) AS TOTAL
FROM CONTAS_A_RECEBER cr
JOIN CLIENTE c ON c.ID = cr.ID_CLIENTE
GROUP BY cr.ID_CLIENTE, c.NOME, cr.STATUS;


CREATE OR REPLACE VIEW vw_concertos_ativos AS
SELECT 
    co.ID,
    cli.NOME AS CLIENTE,
    co.PROBLEMA_DESCRITO,
    co.SITUACAO,
    co.DATA_ENTRADA,
    co.OBSERVACAO
FROM CONCERTO_OCULOS co
JOIN CLIENTE cli ON cli.ID = co.ID_CLIENTE
WHERE co.SITUACAO IN ('EM ANÁLISE', 'EM REPARO', 'AGUARDANDO PEÇA');


CREATE OR REPLACE VIEW vw_status_pedido_cliente AS
SELECT 
    p.ID,
    c.NOME AS CLIENTE,
    p.STATUS,
    p.DATA_PEDIDO,
    p.DATA_ENVIO,
    p.TOTAL
FROM PEDIDO_ECOMMERCE p
JOIN CLIENTE c ON c.ID = p.ID_CLIENTE;

